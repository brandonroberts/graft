import { mkdir, mkdtemp, readFile, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import { detectPackageManager, DirectoryUpstreamSource, findInstalledPackage, Project, readInstalledFiles } from '@graftsync/core';
import { graftApplier, patchAdapter, patchPackageApplier, selectApplier, vendorApplier, yarnApplier, yarnPatchSpec } from '../src/index.js';

const VARIANT = 'diff --git a/index.js b/index.js\nindex 111..222 100644\n--- a/index.js\n+++ b/index.js\n@@ -1,2 +1,3 @@\n a\n+b\n c\n';

async function project(manifest: Record<string, unknown>, files: Record<string, string> = {}) {
  const root = await mkdtemp(path.join(os.tmpdir(), 'graft-yarn-'));
  await writeFile(path.join(root, 'package.json'), `${JSON.stringify(manifest, null, 2)}\n`);
  for (const [f, content] of Object.entries(files)) await writeFile(path.join(root, f), content);
  const variant = path.join(root, '.grafts/g/variants/v1.patch');
  await mkdir(path.dirname(variant), { recursive: true });
  await writeFile(variant, VARIANT);
  return { root, variant, manifest: async () => JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8')) };
}

const BERRY_LOCK = '# This file is generated by running "yarn install" inside your project.\n\n__metadata:\n  version: 8\n  cacheKey: 10c0\n';
const CLASSIC_LOCK = '# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n';

/**
 * A stand-in for yarn's .pnp.cjs: preloaded with `node -r`, it serves `require('pnpapi')`, and
 * resolves `lib` to `<root>/store/lib/` (yarn's real runtime resolves into its zip cache).
 */
const FAKE_PNP = `
const Module = require('module'), path = require('path');
const original = Module._resolveFilename;
Module._resolveFilename = function (request, ...rest) { return request === 'pnpapi' ? __filename : original.call(this, request, ...rest); };
module.exports = { resolveToUnqualified: (pkg) => { if (pkg !== 'lib') throw new Error('not a dependency'); return path.join(__dirname, 'store', 'lib') + '/'; } };
`;

describe('yarn classic vs berry detection', () => {
  it('tells berry from classic by packageManager, .yarnrc.yml, .pnp.cjs, or the lockfile header', async () => {
    expect(detectPackageManager((await project({}, { 'yarn.lock': CLASSIC_LOCK })).root)).toBe('yarn');
    expect(detectPackageManager((await project({}, { 'yarn.lock': '' })).root)).toBe('yarn');
    expect(detectPackageManager((await project({}, { 'yarn.lock': BERRY_LOCK })).root)).toBe('yarn-berry');
    expect(detectPackageManager((await project({}, { 'yarn.lock': '', '.yarnrc.yml': 'nodeLinker: node-modules\n' })).root)).toBe('yarn-berry');
    expect(detectPackageManager((await project({}, { 'yarn.lock': '', '.pnp.cjs': '' })).root)).toBe('yarn-berry');
    expect(detectPackageManager((await project({ packageManager: 'yarn@4.18.1' })).root)).toBe('yarn-berry');
    expect(detectPackageManager((await project({ packageManager: 'yarn@1.22.22' }, { 'yarn.lock': CLASSIC_LOCK })).root)).toBe('yarn');
    // An explicit classic packageManager wins over stray berry markers.
    expect(detectPackageManager((await project({ packageManager: 'yarn@1.22.22' }, { '.yarnrc.yml': '' })).root)).toBe('yarn');
  });

  it('defaults berry to the yarn applier and classic to the built-in one', async () => {
    expect(selectApplier((await project({ packageManager: 'yarn@4.18.1' })).root).name).toBe('yarn');
    expect(selectApplier((await project({}, { 'yarn.lock': BERRY_LOCK })).root).name).toBe('yarn');
    expect(selectApplier((await project({}, { 'yarn.lock': CLASSIC_LOCK })).root).name).toBe('graft');
  });
});

describe('yarn applier (berry patch: protocol)', () => {
  it('builds the patch: descriptor yarn expects', () => {
    expect(yarnPatchSpec('ms', '2.1.2', '.grafts/ms/variants/v1.patch')).toBe('patch:ms@npm%3A2.1.2#./.grafts/ms/variants/v1.patch');
    expect(yarnPatchSpec('@scope/lib', '1.0.0', '../shared/v1.patch')).toBe('patch:@scope/lib@npm%3A1.0.0#../shared/v1.patch');
  });

  it('writes a name-only resolution, bumps the declared version, and tracks upgrades', async () => {
    const p = await project(
      { name: 'app', packageManager: 'yarn@4.18.1', dependencies: { lib: '^1.0.0' }, devDependencies: { other: '1.0.0' }, resolutions: { 'lib@npm:^1.0.0': '1.0.1', other: '1.0.0' } },
      { 'yarn.lock': BERRY_LOCK },
    );
    const before = (await yarnApplier.problems(p.root, 'lib', '1.2.0', p.variant)).join('\n');
    expect(before).toMatch(/resolutions\["lib"\] must be "patch:lib@npm%3A1\.2\.0#\.\/\.grafts\/g\/variants\/v1\.patch"/);
    expect(before).toMatch(/resolutions\["lib@npm:\^1\.0\.0"\] also resolves lib/);
    expect(await yarnApplier.configure(p.root, 'lib', '1.2.0', p.variant)).toMatchObject({ install: 'reinstall' });
    const m = await p.manifest();
    expect(m.resolutions).toEqual({ other: '1.0.0', lib: 'patch:lib@npm%3A1.2.0#./.grafts/g/variants/v1.patch' });
    expect(m.dependencies).toEqual({ lib: '^1.2.0' });
    expect(await yarnApplier.problems(p.root, 'lib', '1.2.0', p.variant)).toEqual([]);
    // An upgrade must move the resolution, or yarn keeps installing the old patched version.
    expect((await yarnApplier.problems(p.root, 'lib', '1.3.0', p.variant)).join('\n')).toMatch(/must be "patch:lib@npm%3A1\.3\.0#/);
  });

  it('flags a patch: dependency left by `yarn patch-commit` and replaces it', async () => {
    const p = await project({ name: 'app', packageManager: 'yarn@4.18.1', dependencies: { lib: 'patch:lib@npm%3A1.0.0#~/.yarn/patches/lib-npm-1.0.0-abc.patch' } });
    expect((await yarnApplier.problems(p.root, 'lib', '1.0.0', p.variant)).join('\n')).toMatch(/dependencies\["lib"\] is a patch: descriptor/);
    await yarnApplier.configure(p.root, 'lib', '1.0.0', p.variant);
    expect((await p.manifest()).dependencies).toEqual({ lib: '1.0.0' });
    expect(await yarnApplier.problems(p.root, 'lib', '1.0.0', p.variant)).toEqual([]);
  });

  it('refuses yarn classic, which has no patch: protocol', async () => {
    const p = await project({ name: 'app' }, { 'yarn.lock': CLASSIC_LOCK });
    expect((await yarnApplier.problems(p.root, 'lib', '1.0.0', p.variant)).join('\n')).toMatch(/needs yarn 2\+ \(berry\)/);
    await expect(yarnApplier.configure(p.root, 'lib', '1.0.0', p.variant)).rejects.toThrow(/needs yarn 2\+/);
  });

  it('vendor uses resolutions under berry too', async () => {
    const p = await project({ name: 'app', packageManager: 'yarn@4.18.1', dependencies: { lib: '1.0.0' } });
    const dir = path.join(p.root, 'upstream');
    await mkdir(dir);
    await writeFile(path.join(dir, 'package.json'), JSON.stringify({ name: 'lib', version: '1.0.0' }));
    await writeFile(path.join(dir, 'index.js'), 'a\nc\n');
    const upstream = new DirectoryUpstreamSource({ lib: { '1.0.0': dir } });
    await vendorApplier.configure(p.root, 'lib', '1.0.0', p.variant, { upstream });
    const m = await p.manifest();
    expect(m.resolutions).toEqual({ lib: 'file:.grafts/.vendor/lib-1.0.0.tgz' });
    expect(m.dependencies).toEqual({ lib: 'file:.grafts/.vendor/lib-1.0.0.tgz' });
    expect(await vendorApplier.problems(p.root, 'lib', '1.0.0', p.variant, { upstream })).toEqual([]);
  });
});

describe("Plug'n'Play", () => {
  async function pnpProject(installedIndex: string) {
    const p = await project({ name: 'app', packageManager: 'yarn@4.18.1', dependencies: { lib: '1.0.0' } }, { '.pnp.cjs': FAKE_PNP, 'yarn.lock': BERRY_LOCK });
    await mkdir(path.join(p.root, 'store/lib'), { recursive: true });
    await writeFile(path.join(p.root, 'store/lib/package.json'), JSON.stringify({ name: 'lib', version: '1.0.0' }));
    await writeFile(path.join(p.root, 'store/lib/index.js'), installedIndex);
    return p;
  }

  it('resolves the installed version and reads files through the PnP runtime', async () => {
    const p = await pnpProject('a\nb\nc\n');
    const installed = await findInstalledPackage('lib', p.root);
    expect(installed).toMatchObject({ version: '1.0.0', pnp: path.join(p.root, '.pnp.cjs') });
    expect(await readInstalledFiles(installed!, ['index.js', 'missing.js'])).toEqual({ 'index.js': 'a\nb\nc\n', 'missing.js': undefined });
    expect(await findInstalledPackage('not-a-dep', p.root)).toBeUndefined();
  });

  it('refuses the appliers that patch node_modules', async () => {
    const p = await pnpProject('a\nc\n');
    for (const applier of [graftApplier, patchPackageApplier]) {
      expect((await applier.problems(p.root, 'lib', '1.0.0', p.variant)).join('\n')).toMatch(/uses yarn Plug'n'Play/);
      await expect(applier.configure(p.root, 'lib', '1.0.0', p.variant)).rejects.toThrow(/use the "yarn" applier/);
    }
  });

  async function graftProject(installedIndex: string) {
    const p = await pnpProject(installedIndex);
    const g = path.join(p.root, '.grafts', 'g');
    await writeFile(
      path.join(g, 'graft.md'),
      `---\nid: g\nrootstock: { package: lib, verified: 1.0.0 }\nmechanism: patch\nvariants:\n  - range: ">=1.0.0"\n    module: ./variants/v1.patch\noracle: { command: 'node -e "process.exit(0)"' }\n---\n## Why\nw\n## Invariants\ni\n## Where to look\nl\n## Anchors\na\n## History\n- created\n`,
    );
    const pristine = path.join(p.root, 'upstream');
    await mkdir(pristine);
    await writeFile(path.join(pristine, 'package.json'), JSON.stringify({ name: 'lib', version: '1.0.0' }));
    await writeFile(path.join(pristine, 'index.js'), 'a\nc\n');
    class PnpSource extends DirectoryUpstreamSource {
      override installed(pkg: string) {
        return findInstalledPackage(pkg, p.root);
      }
    }
    await yarnApplier.configure(p.root, 'lib', '1.0.0', p.variant);
    const project = await Project.open({ root: p.root, adapters: [patchAdapter], upstream: new PnpSource({ lib: { '1.0.0': pristine } }) });
    return { ...p, project, graft: await project.get('g') };
  }

  it('checks the installed copy inside PnP storage', async () => {
    const good = await graftProject('a\nb\nc\n');
    const ok = await patchAdapter.checkAnchors(good.project.context(good.graft), '1.0.0');
    expect(ok.errors).toEqual([]);
    expect(ok.ok).toBe(true);

    const bad = await graftProject('a\nc\n');
    const report = await patchAdapter.checkAnchors(bad.project.context(bad.graft), '1.0.0');
    expect(report.ok).toBe(false);
    expect(report.errors.join('\n')).toMatch(/installed lib@1\.0\.0 index\.js is not patched/);
  });

  it('warns (without failing) when the installed files cannot be read', async () => {
    const p = await graftProject('a\nb\nc\n');
    const installed = await findInstalledPackage('lib', p.root);
    // The runtime breaks after resolution (e.g. a stale .pnp.cjs): the contents cannot be verified.
    await writeFile(path.join(p.root, '.pnp.cjs'), 'throw new Error("broken runtime")');
    const source = p.project.upstream as DirectoryUpstreamSource;
    source.installed = async () => installed;
    const report = await patchAdapter.checkAnchors(p.project.context(p.graft), '1.0.0');
    expect(report.errors).toEqual([]);
    expect(report.warnings?.join('\n')).toMatch(/cannot verify installed files of lib@1\.0\.0 under Plug'n'Play/);
    expect(report.ok).toBe(true);
  });

  it("refuses `graft apply --installed`, which cannot patch PnP's zip cache", async () => {
    const p = await graftProject('a\nc\n');
    const report = await patchAdapter.applyInstalled!(p.project.context(p.graft));
    expect(report.errors.join('\n')).toMatch(/installed through yarn Plug'n'Play/);
  });
});
